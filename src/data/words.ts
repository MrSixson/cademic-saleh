export function getRandomWords(count: number, excludeIds: string[] = []): WordItem[] {
  const available = WORD_DATABASE.filter(w => !excludeIds.includes(w.id));
  const shuffled = [...available].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, Math.min(count, shuffled.length));
}

export function getWordById(id: string): WordItem | undefined {
  return WORD_DATABASE.find(w => w.id === id);
}

